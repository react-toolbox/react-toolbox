// Rebuild the immutable reference using the original compiler in a temporary directory.
const fs = require('fs');
const path = require('path');
const { createRequire } = require('module');
const legacyRequire = createRequire(path.join(path.resolve(process.argv[2] || '/private/tmp/react-toolbox-legacy-css'), 'package.json'));
const postcss = legacyRequire('postcss');
const root = path.resolve(__dirname, '..');
const fixtures = path.join(root, 'tests/fixtures/legacy-styles');
(async () => {
  const output = [];
  const maps = {};
  const folders = fs.readdirSync(fixtures).filter(name => fs.statSync(path.join(fixtures, name)).isDirectory()).sort();
  for (const folder of folders) {
    const from = path.join(fixtures, folder, 'theme.module.css');
    if (!fs.existsSync(from)) continue;
    const compiled = await postcss([
      legacyRequire('postcss-import')({ root: fixtures, path: fixtures }),
      legacyRequire('postcss-mixins'),
      legacyRequire('postcss-each'),
      legacyRequire('postcss-apply'),
      legacyRequire('postcss-preset-env')({ stage: 0, features: { 'custom-properties': { preserve: false, importFrom: [path.join(fixtures, 'variables.module.css'), path.join(fixtures, 'colors.module.css')] }, 'color-mod-function': true } }),
      legacyRequire('postcss-calc')
    ]).process(fs.readFileSync(from, 'utf8'), { from });
    // css-loader ran after postcss-loader. Keep two separate passes so future
    // CSS transforms do not accidentally transform CSS Modules :export keys.
    const result = await postcss([
      legacyRequire('postcss-modules')({
        generateScopedName: name => `rt-${folder.replaceAll('_', '-')}-${name}`,
        getJSON: (_, json) => { maps[folder] = json; }
      })
    ]).process(compiled.css, { from });
    output.push(`/* Legacy reference: ${folder}. Generated by the original PostCSS pipeline. */\n${result.css}`);
  }
  fs.writeFileSync(path.join(fixtures, 'reference.css'), output.join('\n\n'));
  fs.writeFileSync(path.join(fixtures, 'reference-themes.json'), JSON.stringify(maps, null, 2) + '\n');
  console.log(`Compiled ${folders.length} original component themes.`);
})().catch(error => { console.error(error); process.exitCode = 1; });
